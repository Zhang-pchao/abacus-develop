"""Unit-boundary regressions using native packets, without a DFT executable."""

import json
from pathlib import Path
import re
import tempfile
import unittest

import numpy as np
from ase import Atoms
from ase.calculators.socketio import IPIProtocol
from ase.stress import full_3x3_to_voigt_6_stress

from abacuslite.core import AbacusSocketIO
from abacuslite.io.generalio import read_stru, species_group_indices, write_stru
from abacuslite.io import latestio, legacyio
from abacuslite import units


class PacketSocket:
    """Expose recorded bytes to ASE's real IPIProtocol encoder and decoder."""

    def __init__(self, incoming):
        self.incoming = incoming
        self.sent = []

    def sendall(self, data):
        self.sent.append(data)

    def recv(self, count):
        result = self.incoming[:count]
        self.incoming = self.incoming[count:]
        return result


class TestNativeUnits(unittest.TestCase):
    def setUp(self):
        self.atoms = Atoms(
            "HOH",
            positions=[[0.2, 0.4, 0.6], [1.4, 1.1, 0.3], [0.7, 1.8, 0.5]],
            cell=[[5.0, 0.2, 0.1], [0.4, 6.0, 0.3], [0.2, 0.7, 7.0]],
            pbc=True,
        )

    def test_constants_match_native_source(self):
        header = (
            Path(__file__).resolve().parents[3]
            / "source/source_base/constants.h"
        ).read_text()

        def native(name):
            pattern = rf"^const double {name}\s*=\s*([0-9.eE+-]+)\s*;"
            return float(re.search(pattern, header, re.MULTILINE).group(1))

        self.assertEqual(units.BOHR_TO_ANGSTROM, native("BOHR_TO_A"))
        self.assertEqual(units.RYDBERG_TO_EV, native("Ry_to_eV"))
        self.assertEqual(units.HARTREE_TO_EV, native("Hartree_to_eV"))
        self.assertEqual(units.HARTREE_TO_JOULE, native("HARTREE_SI"))
        self.assertAlmostEqual(
            units.BOHR_TO_ANGSTROM * 1e-10 / native("BOHR_RADIUS_SI"),
            1.0, places=15,
        )

    def test_stru_nonorthogonal_native_angstrom_roundtrip(self):
        with tempfile.TemporaryDirectory() as directory:
            write_stru(self.atoms, directory, {"H": "H.upf", "O": "O.upf"})
            raw = read_stru(Path(directory) / "STRU")

        # Interpret raw STRU fields exactly as the native Cartesian path does.
        # Explicit native values prevent a matching writer/reader error from
        # passing merely because both sides share the same helper.
        scale = raw["lat"]["const"] * 0.5291770
        native_cell = np.asarray(raw["lat"]["vec"]) * scale
        native_positions = np.array([
            atom["coord"]
            for species in raw["species"]
            for atom in species["atom"]
        ]) * scale
        order = species_group_indices(self.atoms.get_chemical_symbols())
        np.testing.assert_allclose(
            native_cell, self.atoms.cell.array, rtol=0, atol=2e-15)
        np.testing.assert_allclose(
            native_positions, self.atoms.positions[order], rtol=0, atol=1e-15)

    def test_socket_native_packets_and_file_geometry_agree(self):
        atoms = self.atoms
        original_positions = atoms.positions.copy()
        original_cell = atoms.cell.array.copy()
        order = species_group_indices(atoms.get_chemical_symbols())
        raw_energy = -17.0  # Hartree on the native wire
        raw_forces = np.arange(1.0, 10.0).reshape(3, 3) / 10
        raw_virial = np.array([
            [2.0, 0.4, 0.2], [0.4, 3.0, 0.6], [0.2, 0.6, 4.0]])
        metadata = json.dumps({
            "schema": "abacus.socket.properties.v1",
            "present": ["energy", "forces", "stress"],
            "scf_converged": True,
        }).encode("utf-8")

        def packet(array, dtype):
            return np.asarray(array, dtype=dtype).tobytes()

        # Raw ABACUS/i-PI response, intentionally not generated by ASE.sendforce.
        incoming = (
            b"READY       " + b"HAVEDATA    " + b"FORCEREADY  "
            + packet([raw_energy], np.float64)
            + packet([len(atoms)], np.int32)
            + packet(raw_forces, np.float64)
            + packet(raw_virial.T, np.float64)
            + packet([len(metadata)], np.int32) + metadata
        )
        transport = PacketSocket(incoming)
        protocol = IPIProtocol(transport)

        class ProtocolServer:
            def calculate(self, wire_atoms):
                return protocol.calculate(wire_atoms.positions, wire_atoms.cell)

        calc = object.__new__(AbacusSocketIO)
        calc._property_constraints = {}
        calc._active_properties = None
        calc._reference_cell = None
        calc.atoms = None
        calc.server = None
        calc._port = None
        calc._unixsocket = "unit-boundary-test"
        calc.launch_server = lambda: ProtocolServer()
        launched = []

        with tempfile.TemporaryDirectory() as directory:
            def launch_client(file_atoms, properties, **kwargs):
                launched.append(file_atoms.copy())
                write_stru(file_atoms, directory, {"H": "H.upf", "O": "O.upf"})
                return None

            calc.launch_client = launch_client
            calc.calculate(atoms, properties=["energy", "forces", "stress"])
            raw_stru = read_stru(Path(directory) / "STRU")

        self.assertTrue(calc.last_scf_converged)
        self.assertEqual(transport.incoming, b"")
        self.assertEqual(transport.sent[0], b"STATUS      ")
        self.assertEqual(transport.sent[1], b"POSDATA     ")
        self.assertEqual(transport.sent[6], b"STATUS      ")
        self.assertEqual(transport.sent[7], b"GETFORCE    ")
        sent_cell = np.frombuffer(transport.sent[2], np.float64).reshape(3, 3).T
        sent_icell = np.frombuffer(transport.sent[3], np.float64).reshape(3, 3).T
        sent_positions = np.frombuffer(
            transport.sent[5], np.float64).reshape(len(atoms), 3)
        np.testing.assert_array_equal(
            np.frombuffer(transport.sent[4], np.int32), [len(atoms)])
        np.testing.assert_allclose(
            sent_cell, original_cell / 0.5291770, rtol=2e-15, atol=0)
        np.testing.assert_allclose(
            sent_icell, np.linalg.pinv(original_cell).T * 0.5291770,
            rtol=2e-14, atol=1e-16)
        np.testing.assert_allclose(
            sent_positions, original_positions[order] / 0.5291770,
            rtol=2e-15, atol=0)
        file_cell = np.asarray(raw_stru["lat"]["vec"]) * raw_stru["lat"]["const"]
        np.testing.assert_allclose(sent_cell, file_cell, rtol=2e-15, atol=0)

        expected_forces = np.empty_like(raw_forces)
        expected_forces[order] = raw_forces * 27.211396 / 0.5291770
        self.assertAlmostEqual(calc.results["energy"], raw_energy * 27.211396)
        self.assertEqual(calc.results["free_energy"], calc.results["energy"])
        np.testing.assert_allclose(
            calc.results["forces"], expected_forces, rtol=2e-15, atol=0)
        expected_stress = (
            -full_3x3_to_voigt_6_stress(raw_virial)
            * 27.211396 / atoms.get_volume())
        np.testing.assert_allclose(
            calc.results["stress"], expected_stress, rtol=2e-15, atol=0)
        np.testing.assert_array_equal(atoms.positions, original_positions)
        np.testing.assert_array_equal(atoms.cell, original_cell)
        np.testing.assert_array_equal(launched[0].positions, original_positions[order])
        np.testing.assert_array_equal(launched[0].cell, original_cell)
        np.testing.assert_array_equal(calc.atoms.cell, original_cell)

    def test_explicit_free_energy_uses_same_native_energy_unit(self):
        from ase.units import Hartree

        class EnergyServer:
            def calculate(self, atoms):
                return {
                    "energy": -17.0 * Hartree,
                    "free_energy": -18.0 * Hartree,
                    "morebytes": b"",
                }

        calc = object.__new__(AbacusSocketIO)
        calc._property_constraints = {}
        calc._active_properties = ("energy",)
        calc._reference_cell = None
        calc.atoms = None
        calc.server = EnergyServer()
        calc.calculate(self.atoms, properties=["free_energy"])
        self.assertAlmostEqual(calc.results["energy"], -17.0 * 27.211396)
        self.assertAlmostEqual(calc.results["free_energy"], -18.0 * 27.211396)

    def test_file_stress_matches_native_energy_per_volume(self):
        stress_ry_bohr3 = np.array([
            [0.01, 0.002, 0.003], [0.002, 0.02, 0.004], [0.003, 0.004, 0.03]])
        # Native output_log.cpp::print_stress conversion, including its older
        # joule constant; this is not ASE's direct physical kbar conversion.
        kbar = stress_ry_bohr3 * (4.35974394e-18 / 2) / (0.529177e-10)**3 * 1e-8
        rows = [" ".join(f"{value:.16f}" for value in row) for row in kbar]
        expected = -stress_ry_bohr3 * 13.605698 / 0.5291770**3
        for module, title in (
            (latestio, "#TOTAL-STRESS (kbar)#"),
            (legacyio, "TOTAL-STRESS (KBAR)"),
        ):
            with self.subTest(reader=module.__name__):
                actual, = module.read_stress_from_running_log([title] + rows)
                np.testing.assert_allclose(actual, expected, rtol=2e-15, atol=0)


if __name__ == "__main__":
    unittest.main()
